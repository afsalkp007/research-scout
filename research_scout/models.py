"""
Domain models for ResearchScout using Pydantic v2.
Strict validation of queries, tool calls, citations, and grounded research reports.
"""

from typing import List, Optional, Dict, Any, Literal
from pydantic import BaseModel, Field, HttpUrl


class SearchResult(BaseModel):
    """A single search result from a web search provider."""
    title: str = Field(..., description="Page title")
    url: str = Field(..., description="Canonical source URL")
    snippet: str = Field(..., description="Relevant text snippet from the page")
    source_domain: Optional[str] = Field(None, description="Extracted domain name (e.g. arxiv.org)")


class ToolCall(BaseModel):
    """A structured function/tool call generated by the research agent."""
    tool_name: str = Field(..., description="Name of the tool to execute")
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Parameters passed to the tool")
    thought: str = Field(..., description="The agent's internal reasoning for invoking this tool")


class AgentStep(BaseModel):
    """A single ReAct reasoning cycle step (Thought -> Action -> Observation)."""
    step_number: int = Field(..., description="1-indexed step in the research trajectory")
    thought: str = Field(..., description="Reasoning before acting")
    tool_call: Optional[ToolCall] = Field(None, description="The tool invocation, if an action was taken")
    observation: Optional[str] = Field(None, description="Result returned by the tool")


class Citation(BaseModel):
    """A verified source citation linking a claim to a verifiable URL."""
    index: int = Field(..., ge=1, description="Numeric reference index (e.g. 1 for [1])")
    title: str = Field(..., description="Title of the source")
    url: str = Field(..., description="Source URL")
    quote_snippet: str = Field(..., description="Verbatim evidence snippet from the source")


class ResearchFinding(BaseModel):
    """A core thesis or discovery supported by explicit citations."""
    claim: str = Field(..., description="High-level factual statement or takeaway")
    explanation: str = Field(..., description="Detailed context and nuances")
    citation_indices: List[int] = Field(
        default_factory=list,
        description="List of citation numbers supporting this finding (e.g. [1, 2])"
    )


class ResearchReport(BaseModel):
    """The synthesized final research briefing."""
    topic: str = Field(..., description="Original research topic or question")
    executive_summary: str = Field(..., description="2-3 paragraph synthesis answering the research query")
    key_findings: List[ResearchFinding] = Field(
        default_factory=list,
        description="Structured key findings with citation references"
    )
    citations: List[Citation] = Field(
        default_factory=list,
        description="All numbered bibliographic citations used in the report"
    )
    confidence_rating: Literal["High", "Medium", "Low"] = Field(
        default="High",
        description="Agent self-assessed reliability based on source diversity and freshness"
    )
    unresolved_questions: List[str] = Field(
        default_factory=list,
        description="Areas where sources were conflicting or insufficient"
    )
    steps_taken: List[AgentStep] = Field(
        default_factory=list,
        description="Full audit trail of reasoning steps and tool calls"
    )
